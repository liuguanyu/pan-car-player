package com.baidu.carplayer.visualizer.breakout;

/**
 * 字符点阵字库：32 字符池 ×（5×7 主力 / 3×5 小号）。
 *
 * <p>字符池 = 数字 0–9 + 剔除 I/O/S/Z 后的 22 个字母。用布尔点阵常量表，
 * 不用系统字体栅格化（方案要求确定性 + 零运行时依赖）。
 *
 * <p>存储：每行一个 int，bit4..bit0 对应左→右 5 列（3 列字体用 bit2..bit0）。
 * 行序自上而下。数据只读，static 初始化一次。
 */
public final class GlyphFont {
    public static final String POOL = "0123456789ABCDEFGHJKLMNPQRTUVWXY";
    public static final int SIZE = POOL.length();

    public static final int BIG_COLS = 5, BIG_ROWS = 7;
    public static final int SMALL_COLS = 3, SMALL_ROWS = 5;

    /** 5×7：每字符 7 行 × 5 bit。索引 = {@link #POOL} 下标。 */
    public static final int[][] G57 = {
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E}, // 0
        {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E}, // 1
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}, // 2
        {0x1F,0x02,0x04,0x02,0x01,0x11,0x0E}, // 3
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}, // 4
        {0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E}, // 5
        {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E}, // 6
        {0x1F,0x01,0x02,0x04,0x08,0x08,0x08}, // 7
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}, // 8
        {0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}, // 9
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11}, // A
        {0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E}, // B
        {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E}, // C
        {0x1E,0x11,0x11,0x11,0x11,0x11,0x1E}, // D
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F}, // E
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x10}, // F
        {0x0E,0x11,0x10,0x17,0x11,0x11,0x0F}, // G
        {0x11,0x11,0x11,0x1F,0x11,0x11,0x11}, // H
        {0x07,0x02,0x02,0x02,0x02,0x12,0x0C}, // J
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11}, // K
        {0x10,0x10,0x10,0x10,0x10,0x10,0x1F}, // L
        {0x11,0x1B,0x15,0x15,0x11,0x11,0x11}, // M
        {0x11,0x19,0x15,0x13,0x11,0x11,0x11}, // N
        {0x1E,0x11,0x11,0x1E,0x10,0x10,0x10}, // P
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D}, // Q
        {0x1E,0x11,0x11,0x1E,0x14,0x12,0x11}, // R
        {0x1F,0x04,0x04,0x04,0x04,0x04,0x04}, // T
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E}, // U
        {0x11,0x11,0x11,0x11,0x11,0x0A,0x04}, // V
        {0x11,0x11,0x11,0x15,0x15,0x1B,0x11}, // W
        {0x11,0x11,0x0A,0x04,0x0A,0x11,0x11}, // X
        {0x11,0x11,0x0A,0x04,0x04,0x04,0x04}, // Y
    };

    /** 3×5：每字符 5 行 × 3 bit。T 模板（4 字形）用的小号字库。 */
    public static final int[][] G35 = {
        {7,5,5,5,7}, // 0
        {2,6,2,2,7}, // 1
        {7,1,7,4,7}, // 2
        {7,1,3,1,7}, // 3
        {5,5,7,1,1}, // 4
        {7,4,7,1,7}, // 5
        {7,4,7,5,7}, // 6
        {7,1,1,2,2}, // 7
        {7,5,7,5,7}, // 8
        {7,5,7,1,7}, // 9
        {2,5,7,5,5}, // A
        {6,5,6,5,6}, // B
        {7,4,4,4,7}, // C
        {6,5,5,5,6}, // D
        {7,4,6,4,7}, // E
        {7,4,6,4,4}, // F
        {7,4,5,5,7}, // G
        {5,5,7,5,5}, // H
        {3,1,1,5,2}, // J
        {5,6,4,6,5}, // K
        {4,4,4,4,7}, // L
        {5,7,7,5,5}, // M
        {6,5,5,5,5}, // N
        {7,5,7,4,4}, // P
        {2,5,5,7,1}, // Q
        {7,5,6,5,5}, // R
        {7,2,2,2,2}, // T
        {5,5,5,5,7}, // U
        {5,5,5,5,2}, // V
        {5,5,7,7,5}, // W
        {5,2,2,2,5}, // X
        {5,5,2,2,2}, // Y
    };

    private GlyphFont() { }

    /** 字符是否在池中；返回池内下标，否则 -1。 */
    public static int indexOf(char c) {
        if (c >= '0' && c <= '9') return c - '0';
        if (c >= 'A' && c <= 'Z') {
            int i = POOL.indexOf(c);
            return i;
        }
        return -1;
    }

    /** 大字 5×7 的 (row, col) 是否点亮。row 0=顶。 */
    public static boolean cell57(int key, int row, int col) {
        return (G57[key][row] & (1 << (BIG_COLS - 1 - col))) != 0;
    }

    /** 小字 3×5 的 (row, col) 是否点亮。 */
    public static boolean cell35(int key, int row, int col) {
        return (G35[key][row] & (1 << (SMALL_COLS - 1 - col))) != 0;
    }

    /** 大字亮格数（供上限检查与 ASCII 校验）。 */
    public static int litCount57(int key) {
        int n = 0;
        for (int r = 0; r < BIG_ROWS; r++)
            for (int c = 0; c < BIG_COLS; c++)
                if (cell57(key, r, c)) n++;
        return n;
    }
}
